#!/usr/bin/env node
// Regenerates every app icon file from src/lib/appIconGeometry.ts (§416): the desktop
// icon set (src-tauri/icons), the web app's icons, the website's and demo's favicons and header logo, and
// the 1024 px master in docs/design. Rasterized with Playwright's Chromium (already a dev
// dependency), so the pixel-fitted small sizes come out exactly as drawn; replaces
// `npx tauri icon`, which only scales one master down.
//
//   node scripts/build-icons.mjs
//
// website/webapp and website/demo-app are release artifacts and pick the new files up at
// the next release (§ webapp/desktop release coupling).

import { chromium } from "playwright";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { appIconSvg, appIconPlateSvg } from "../src/lib/appIconGeometry.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ICO_SIZES = [16, 20, 24, 30, 32, 36, 40, 48, 64, 256];

const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });

async function png(svg, size) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<style>html,body{margin:0;background:transparent}svg{display:block}</style>${svg}`);
  return page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
}

function ico(frames) {
  // PNG-compressed ICO entries (supported since Windows Vista).
  const header = Buffer.alloc(6 + 16 * frames.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(frames.length, 4);
  let offset = header.length;
  frames.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size % 256, e);
    header.writeUInt8(size % 256, e + 1);
    header.writeUInt16LE(1, e + 4);
    header.writeUInt16LE(32, e + 6);
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...frames.map((f) => f.data)]);
}

function write(rel, data) {
  const path = join(root, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, data);
  console.log(`  ${rel}`);
}

const frames = [];
for (const size of ICO_SIZES) frames.push({ size, data: await png(appIconSvg(size), size) });
const icoFile = ico(frames);
const at = (size) => frames.find((f) => f.size === size)?.data;

// Desktop app (tauri.conf.json bundle.icon).
write("src-tauri/icons/icon.ico", icoFile);
write("src-tauri/icons/32x32.png", at(32));
write("src-tauri/icons/128x128.png", await png(appIconSvg(128), 128));
write("src-tauri/icons/128x128@2x.png", at(256));
write("src-tauri/icons/256x256.png", at(256));

// Web app: transparent "any" icons; maskable ones on a full-bleed plate with the glyph
// inside the ~60 % safe zone (Android masks them to a circle or squircle). iOS fills
// transparency with black and rounds the corners itself, so its home-screen icon is the
// plated one too (webapp-src/index.html's apple-touch-icon links).
const plate = await png(appIconPlateSvg(256, 0.6), 256);
write("webapp-src/public/icons/icon-256.png", at(256));
write("webapp-src/public/icons/icon-512.png", await png(appIconSvg(512), 512));
write("webapp-src/public/icons/icon-256-maskable.png", plate);
write("webapp-src/public/icons/icon-512-maskable.png", await png(appIconPlateSvg(512, 0.6), 512));

// Website and demo favicons, with the same plated iOS icon. (The social preview is a page of its own since §440:
// scripts/build-og-image.mjs.)
const touch = plate;
for (const dir of ["website/assets", "demo-src/public"]) {
  write(`${dir}/favicon.ico`, icoFile);
  write(`${dir}/favicon-32.png`, at(32));
  write(`${dir}/apple-touch-icon.png`, touch);
}
// The website header's logo (§436), pixel-fitted at its 20 px.
write("website/assets/logo.svg", appIconSvg(20) + "\n");

// The 1024 px master, for design work and history: a title and description right after
// the opening <svg> tag.
const master = appIconSvg(1024);
const afterOpenTag = master.indexOf(">") + 1;
write(
  "docs/design/icon-A-master.svg",
  master.slice(0, afterOpenTag) +
    '\n  <title>ChronoNote app icon: "daily agenda", no tile (§416)</title>\n' +
    "  <desc>Generated by scripts/build-icons.mjs from src/lib/appIconGeometry.ts; edit that file, not this one.</desc>\n  " +
    master.slice(afterOpenTag) +
    "\n",
);

await browser.close();
